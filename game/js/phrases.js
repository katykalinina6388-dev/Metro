  M.phrase = function (id) {
    const p = id.split('.'), S = M.LINE.stations;
    if (p[0] === 'c') return 'Диспетчер, маршрут ' + M.numWords(+p[1]) + '.';
    if (p[0] === 'sc') return 'Диспетчер, станция ' + S[+p[1]].name + '.';
    if (p[0] === 'd') return M.PH.d[p[1]] || '';
    if (p[0] === 's') return M.PH.s[p[1]] || '';
    if (p[0] === 'ds') return (M.PH.ds[p[1]] || '').replace('{n}', S[+p[2]].name);
    return '';
  };

  /** Полный перечень фрагментов для генератора озвучки: {id, text, who}. */
  M.allClips = function () {
    const out = [], S = M.LINE.stations;
    for (let n = 1; n <= M.LINE.fleet; n++) out.push({ id: 'c.' + n, who: 'driver' });
    for (const k in M.PH.d) out.push({ id: 'd.' + k, who: 'driver' });
    for (const k in M.PH.ds) for (let i = 0; i < S.length; i++) out.push({ id: 'ds.' + k + '.' + i, who: 'driver' });
    for (let i = 0; i < S.length; i++) out.push({ id: 'sc.' + i, who: 'station' });
    for (const k in M.PH.s) out.push({ id: 's.' + k, who: 'station' });
    for (const c of out) c.text = M.phrase(c.id);
    return out;
  };
